import { downloadTemplate } from "giget";
import { copyFile, mkdir, readdir, readlink, rm, symlink, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { readPluginVersions } from "./versions.js";

export type TemplateSource = { kind: "github"; ref: string } | { kind: "local"; path: string };

const PRUNE_PATHS = [
  // Plugin source — users consume them as published npm packages instead.
  "packages/payload-plugin-ab",
  "packages/payload-plugin-analytics",
  "packages/payload-plugin-audit-log",
  "packages/payload-plugin-comments",
  "packages/payload-plugin-json-form-builder",
  "packages/payload-plugin-presets",
  "packages/payload-plugin-scheduling",
  "packages/payload-plugin-seo",
  "packages/payload-plugin-stacked-editing",
  "packages/payload-plugin-translator",
  "packages/payload-plugin-visual-editing",
  "packages/payload-plugin-ai-page-builder",
  // The CLI itself — its source lives inside the monorepo and must not bleed into scaffolded projects.
  "packages/create-ideal-cms",
  // Internal example/demo apps — only useful inside the source monorepo.
  "apps/dev",
  "apps/multi-tenancy-demo",
  "apps/content-agent-demo",
  // Release machinery — not relevant downstream.
  ".releaserc.json",
  ".github",
  // Internal repo bookkeeping.
  "skills-lock.json",
  "docs",
  "CLAUDE.md",
  ".cursor",
  // Lockfile gets regenerated by the user's package manager.
  "bun.lock",
  // Any caches / build artifacts that may have slipped through.
  ".turbo",
  "apps/cms/.turbo",
  "apps/cms/.next",
  "apps/cms/.env",
  "apps/cms/test.env",
] as const;

// When copying from a local source repo we skip these at any depth to avoid
// dragging huge generated trees and the upstream .git history. `.test-output`
// is here so `bun run test:local` (which scaffolds INTO that dir) can still
// use the monorepo itself as the source without infinite recursion.
const LOCAL_COPY_SKIP = new Set([
  "node_modules",
  ".next",
  ".turbo",
  "dist",
  ".git",
  ".DS_Store",
  ".test-output",
]);

const MIGRATION_STUB = `// Regenerated by create-ideal-cms.
// Run \`<pm> run payload migrate:create init\` to populate this index.
export const migrations: { up: () => Promise<void>; down: () => Promise<void>; name: string }[] = []
`;

// `.github` is pruned above because the source repo's workflows are its own release machinery.
// This one job is written back: the Neon and Vercel integration creates a `preview/<branch>`
// database branch per preview deployment and never removes it. The job skips when the new
// repository has no Neon key, because the integration does not set one and the scaffold cannot.
const NEON_CLEANUP_WORKFLOW = `name: Cleanup Neon preview branch

# The Neon<->Vercel integration creates a \`preview/<git-branch>\` database branch for each
# preview deployment but never removes it. Delete it when the pull request closes, merged or
# not, so stale branches do not pile up storage costs.
#
# Needs the repository variable NEON_PROJECT_ID and the repository secret NEON_API_KEY.
# Without them the job skips instead of failing.
on:
  pull_request:
    types: [closed]

permissions: {}

jobs:
  delete-branch:
    runs-on: ubuntu-latest
    # Fork pull requests get no Neon preview branch and cannot read repository secrets.
    if: github.event.pull_request.head.repo.full_name == github.repository
    env:
      NEON_API_KEY: \${{ secrets.NEON_API_KEY }}
      NEON_PROJECT_ID: \${{ vars.NEON_PROJECT_ID }}
    steps:
      - name: Skip when Neon is not configured
        if: env.NEON_API_KEY == '' || env.NEON_PROJECT_ID == ''
        run: echo "NEON_API_KEY or NEON_PROJECT_ID is not set in this repository, so no Neon branch was deleted."
      - uses: neondatabase/delete-branch-action@v3
        if: env.NEON_API_KEY != '' && env.NEON_PROJECT_ID != ''
        with:
          project_id: \${{ vars.NEON_PROJECT_ID }}
          branch: preview/\${{ github.head_ref }}
          api_key: \${{ secrets.NEON_API_KEY }}
`;

async function writeNeonCleanupWorkflow(targetDir: string): Promise<void> {
  const dir = join(targetDir, ".github/workflows");
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, "neon-cleanup.yml"), NEON_CLEANUP_WORKFLOW);
}

// Manual recursive copy. Replaces `fs.cp` because that errors with EINVAL when
// `dest` is a subdirectory of `src` — which is exactly what `bun run test:local`
// does (scaffolds into `.test-output` inside the source monorepo).
async function copyLocal(src: string, dest: string): Promise<void> {
  await mkdir(dest, { recursive: true });
  const entries = await readdir(src, { withFileTypes: true });
  await Promise.all(
    entries.map(async (entry) => {
      if (LOCAL_COPY_SKIP.has(entry.name)) return;
      const sp = join(src, entry.name);
      const dp = join(dest, entry.name);
      if (entry.isSymbolicLink()) {
        const target = await readlink(sp);
        await symlink(target, dp);
      } else if (entry.isDirectory()) {
        await copyLocal(sp, dp);
      } else if (entry.isFile()) {
        await copyFile(sp, dp);
      }
    })
  );
}

async function resetMigrations(targetDir: string): Promise<void> {
  const dir = join(targetDir, "apps/cms/src/lib/database/migrations");
  let entries: string[];
  try {
    entries = await readdir(dir);
  } catch {
    return;
  }
  await Promise.all(
    entries
      .filter((e) => e !== "index.ts")
      .map((e) => rm(join(dir, e), { recursive: true, force: true }))
  );
  await writeFile(join(dir, "index.ts"), MIGRATION_STUB);
}

export async function fetchTemplate(
  targetDir: string,
  source: TemplateSource
): Promise<Record<string, string>> {
  if (source.kind === "local") {
    await copyLocal(source.path, targetDir);
  } else {
    await downloadTemplate(`gh:focusreactive/payload-plugins#${source.ref}`, {
      dir: targetDir,
      force: false,
      preferOffline: false,
      install: false,
    });
  }

  const pluginVersions = await readPluginVersions(targetDir);

  await Promise.all(
    PRUNE_PATHS.map((path) => rm(join(targetDir, path), { recursive: true, force: true }))
  );

  await resetMigrations(targetDir);
  await writeNeonCleanupWorkflow(targetDir);

  return pluginVersions;
}
